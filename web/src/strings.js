export function getDashLang() {
  let l = null;
  try { l = localStorage.getItem('sm_dash_lang'); } catch (e) {}
  if (l === 'tr' || l === 'en') return l;
  const nav = (navigator.language || 'en').toLowerCase();
  return nav.indexOf('tr') === 0 ? 'tr' : 'en';
}
